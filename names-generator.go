// GetRandomName generates a random name from the list of adjectives and animals in this package
// formatted as "adjective_animal". For example 'focused_squirrel'. If retry is non-zero, a random
// integer between 0 and 10 will be added to the end of the name, e.g `focused_squirrel3`
func GetRandomName(retry int) string {
	name := left[rand.Intn(len(left))] + "_" + right[rand.Intn(len(right))] //nolint:gosec // G404: Use of weak random number generator (math/rand instead of crypto/rand)

	if retry > 0 {
		name += strconv.Itoa(rand.Intn(10)) //nolint:gosec // G404: Use of weak random number generator (math/rand instead of crypto/rand)
	}

	return name
}
